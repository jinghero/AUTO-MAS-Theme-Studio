const fs = require('node:fs')
const path = require('node:path')
const { createRequire } = require('node:module')
const dep = createRequire(path.join(__dirname, 'package.json'))
const AdmZip = dep('adm-zip')
const asar = dep('@electron/asar')
const root = __dirname
async function build() {
  // 将运行时 ZIP 依赖带入 app.asar，便携版不依赖开发目录。
  const vendor = path.join(root, 'app/node_modules/adm-zip')
  fs.mkdirSync(path.dirname(vendor), { recursive: true })
  fs.cpSync(path.dirname(dep.resolve('adm-zip')), vendor, { recursive: true })
  const output = path.join(root, 'dist', 'MAS创作工具箱')
  fs.mkdirSync(output, { recursive: true })
  const runtime = path.join(path.dirname(dep.resolve('electron')), 'dist')
  fs.cpSync(runtime, output, { recursive: true, filter: file => path.basename(file) !== 'default_app.asar' })
  const executable = path.join(output, 'MAS主题工坊.exe')
  if (fs.existsSync(executable)) fs.unlinkSync(executable)
  fs.renameSync(path.join(output, 'electron.exe'), executable)
  await asar.createPackage(path.join(root, 'app'), path.join(output, 'resources', 'app.asar'))
  for (const name of ['使用说明.txt', '示例主题-林间来信.zip', '示例桌宠.zip']) fs.copyFileSync(path.join(root, name), path.join(output, name))
  fs.copyFileSync(path.join(root, 'app/LICENSE'), path.join(output, 'LICENSE-AGPL-3.0.txt'))
  fs.copyFileSync(path.join(root, 'app/node_modules/adm-zip/LICENSE'), path.join(output, 'LICENSE-adm-zip.txt'))
  fs.copyFileSync(path.join(root, 'app/compat/SOURCE.txt'), path.join(output, '兼容版本.txt'))
  const source = new AdmZip()
  source.addLocalFolder(path.join(root, 'app'), 'app')
  source.addLocalFolder(path.join(root, 'preview-src'), 'preview-src')
  for (const name of ['package.json', 'package-lock.json', 'run.cjs', 'README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', '.gitignore', 'setup.cjs', 'build.cjs', 'prepare-preview.cjs', 'build-preview.cjs', 'verify-mas.cjs', 'verify.cjs', 'verify-extra.cjs', 'verify-ai.cjs', 'verify-theme.cjs', '使用说明.txt']) source.addLocalFile(path.join(root, name))
  source.addFile('README.txt', Buffer.from('完整源码位于 app/ 与 preview-src/。\n开发环境安装 Node.js 22.16 或更新版本，在本目录运行 npm ci、npm start。\n便携版打包：npm run build:preview，然后 npm run build。\n便携运行无需 Node.js 或额外依赖；许可见 LICENSE 和 THIRD_PARTY_NOTICES.md。\n'))
  source.writeZip(path.join(output, 'source.zip'))
  const zipPath = path.join(root, 'dist', 'MAS创作工具箱-便携版.zip')
  const archive = new AdmZip()
  archive.addLocalFolder(output, 'MAS主题工坊')
  // 开发和验证时产生的 data 不属于分发包。
  for (const entry of archive.getEntries()) if (entry.entryName.startsWith('MAS主题工坊/data/')) archive.deleteFile(entry)
  archive.writeZip(zipPath)
  console.log(JSON.stringify({ executable, zipPath, sizeMiB: +(fs.statSync(zipPath).size / 1024 / 1024).toFixed(1) }))
}
build().catch(error => { console.error(error); process.exitCode = 1 })
